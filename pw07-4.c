// При передаче по значению создаётся копия, не влияющая на оригинал
// При передачи по указателю ф-ия получает адрес переменной и может изменять её значение в памяти

#include <stdio.h> // V - 18

void remaind (int *a, int *b); // прототип процедуры, принимающий два указателя на целые числа

int main() {
    int a, b;

    printf ("Введите 2 целых числа: ");
    if (scanf ("%d %d", &a, &b) == 2)
    {
        printf ("Исходные значения: a = %d, b = %d\n", a, b);
        remaind (&a, &b);
        printf ("Измененные значения: a = %d, b = %d\n", a, b);
    }
    else
    {
        printf ("Ошибка: некорректный ввод\n");
    }

    return 0;
}

void remaind (int *a, int *b)
{
    int rem;

    if (*a >= *b)   // Разименование (получение самого значение из адреса)
    {
        if (*b == 0)
        {
            printf ("Ошибка: деление на ноль\n");
            return;
        }
        rem = *a % *b;
    }
    else
    {
        if (*a == 0)
        {
            printf ("Ошибка: деление на ноль\n");
            return;
        }
        rem = *b % *a;
    }
    *a = rem;
    *b = rem;
}